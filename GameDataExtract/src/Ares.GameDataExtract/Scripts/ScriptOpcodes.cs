namespace Ares.GameDataExtract.Scripts;

/// <summary>
/// Operand layout of a script bytecode instruction, after the opcode byte: <c>Word</c> is a 16-bit argument in the
/// upper half of the first 32-bit word (<c>Write</c>/<c>Read</c> mark a frame variable written or read), <c>DoubleWord</c>
/// one more 32-bit word, <c>QuadWord</c> two (a 64-bit value or cook-time reference).
/// </summary>
internal enum ScriptOperandLayout
{
    None,
    Word,
    WriteWord,
    DoubleWord,
    ReadWordDoubleWord,
    QuadWord,
    WriteReadReadWord,
    WriteWordQuadWord,
    WriteReadWord,
    ReadWord,
    WriteWordDoubleWord,
    WriteReadWordDoubleWord,
    ReadReadWord,
    QuadWordDoubleWord,
    ReadWordQuadWord,
    WordDoubleWord,
    ReadWordWordDoubleWord,
    ReadWordDoubleWordDoubleWord,
    WordReadWord,
}

/// <summary>
/// One script bytecode instruction kind: its name, operand layout and how many 32-bit stack slots it pushes (positive)
/// or pops (negative); <see langword="null"/> when that depends on the operands (calls, returns).
/// </summary>
internal sealed record ScriptOpcode(string Name, ScriptOperandLayout Layout, int? StackChange)
{
    /// <summary>Instruction length in 32-bit words, opcode word included.</summary>
    public int Size => Layout switch
    {
        ScriptOperandLayout.None or ScriptOperandLayout.Word or ScriptOperandLayout.WriteWord or ScriptOperandLayout.ReadWord => 1,
        ScriptOperandLayout.QuadWord or ScriptOperandLayout.WriteWordQuadWord
            or ScriptOperandLayout.WriteReadWordDoubleWord or ScriptOperandLayout.ReadWordQuadWord
            or ScriptOperandLayout.ReadWordWordDoubleWord or ScriptOperandLayout.ReadWordDoubleWordDoubleWord => 3,
        ScriptOperandLayout.QuadWordDoubleWord => 4,
        _ => 2,
    };

    /// <summary>Whether the 16-bit argument names a frame variable the instruction writes.</summary>
    public bool WritesVariable => Layout is ScriptOperandLayout.WriteWord or ScriptOperandLayout.WriteReadReadWord
        or ScriptOperandLayout.WriteWordQuadWord or ScriptOperandLayout.WriteReadWord or ScriptOperandLayout.WriteWordDoubleWord
        or ScriptOperandLayout.WriteReadWordDoubleWord;
}

